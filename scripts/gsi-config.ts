// yarn gsi:config [--install] [--print]
//
// Writes the CS2 Game State Integration config for CS2Live into CS2LIVE_DATA_DIR (default
// .cs2live/). With --install it also copies it into CS2's cfg folder. Reads GSI_TOKEN and
// GSI_URL from the environment (.env is loaded by the yarn script). If GSI_TOKEN is missing a
// new random token is generated and appended to .env.
import { randomBytes } from 'node:crypto';
import {
	appendFileSync,
	copyFileSync,
	existsSync,
	mkdirSync,
	readFileSync,
	writeFileSync
} from 'node:fs';
import { join, resolve } from 'node:path';
import { findCs2CfgDir } from '../src/lib/server/gsi/cs2-paths.ts';
import { renderGsiConfig, GSI_CONFIG_FILENAME } from '../src/lib/server/gsi/gsi-template.ts';

const args = new Set(process.argv.slice(2));
const envFile = resolve('.env');

let token = process.env.GSI_TOKEN;
if (!token) {
	token = randomBytes(24).toString('hex');
	const existing = existsSync(envFile) ? readFileSync(envFile, 'utf8') : '';
	const prefix = existing === '' || existing.endsWith('\n') ? '' : '\n';
	appendFileSync(
		envFile,
		`${prefix}\n# Shared secret CS2 sends with every GSI post (generated by yarn gsi:config)\nGSI_TOKEN=${token}\n`
	);
	console.log(`GSI_TOKEN was not set, so a new one was generated and added to ${envFile}.`);
	console.log('Restart `yarn dev` / `yarn live` so the server picks it up.\n');
}

const url = process.env.GSI_URL || 'http://127.0.0.1:5173/api/gsi';
const cfg = renderGsiConfig({ url, token });

const dataDir = resolve(process.env.CS2LIVE_DATA_DIR || '.cs2live');
mkdirSync(dataDir, { recursive: true });
const localPath = join(dataDir, GSI_CONFIG_FILENAME);
writeFileSync(localPath, cfg);
console.log(`Wrote ${localPath}`);
console.log(`  endpoint: ${url}`);

if (args.has('--print')) console.log('\n' + cfg);

const cfgDir = findCs2CfgDir();
if (args.has('--install')) {
	if (!cfgDir) {
		console.error(
			'\nCould not find the CS2 cfg folder. Set CS2_CFG_DIR to ' +
				'...\\steamapps\\common\\Counter-Strike Global Offensive\\game\\csgo\\cfg and run again.'
		);
		process.exit(1);
	}
	const target = join(cfgDir, GSI_CONFIG_FILENAME);
	try {
		copyFileSync(localPath, target);
	} catch (err) {
		console.error(`\nCould not write ${target}: ${(err as Error).message}`);
		console.error(
			'Copy the file there by hand, or run this from a terminal opened as administrator.'
		);
		process.exit(1);
	}
	console.log(`Installed ${target}`);
	console.log('Restart CS2 (it only reads GSI configs at startup).');
} else {
	console.log('\nTo install it, run `yarn gsi:config --install`, or copy the file into:');
	console.log(
		`  ${cfgDir ?? '...\\Steam\\steamapps\\common\\Counter-Strike Global Offensive\\game\\csgo\\cfg'}`
	);
	console.log('then restart CS2.');
}
